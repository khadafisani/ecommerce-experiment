CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, email VARCHAR(254) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, password VARCHAR(255) NOT NULL, admin BOOLEAN NOT NULL DEFAULT FALSE, suspended BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS shops (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, owner_id BIGINT NOT NULL REFERENCES users(id), suspended BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS members (
    shop_id BIGINT NOT NULL REFERENCES shops(id), user_id BIGINT NOT NULL REFERENCES users(id), PRIMARY KEY(shop_id,user_id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS sessions (
    id CHAR(36) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), refresh_hash CHAR(64) NOT NULL, expires_at DATETIME NOT NULL, revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS password_resets (
    token_hash CHAR(64) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at DATETIME NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS login_limits (
    identity_hash CHAR(64) NOT NULL, window_start BIGINT NOT NULL, attempts INT NOT NULL, PRIMARY KEY(identity_hash,window_start),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS taxonomy (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, kind ENUM('brand','category') NOT NULL, name VARCHAR(120) NOT NULL, status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending', UNIQUE(kind,name),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS products (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, shop_id BIGINT NOT NULL REFERENCES shops(id), name VARCHAR(180) NOT NULL, description TEXT NOT NULL, image VARCHAR(255) NOT NULL DEFAULT '', brand_id BIGINT REFERENCES taxonomy(id), category_id BIGINT REFERENCES taxonomy(id), status ENUM('pending','active','inactive','rejected') NOT NULL DEFAULT 'pending', note VARCHAR(1000) NOT NULL DEFAULT '', actor_id BIGINT NOT NULL REFERENCES users(id), INDEX(status,id), INDEX(shop_id,id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS variants (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL REFERENCES products(id), name VARCHAR(150) NOT NULL, subvariant VARCHAR(150) NOT NULL DEFAULT '', price BIGINT NOT NULL CHECK(price BETWEEN 1 AND 1000000000), stock INT NOT NULL CHECK(stock BETWEEN 0 AND 100000000), grams INT NOT NULL CHECK(grams BETWEEN 1 AND 1000000), enabled BOOLEAN NOT NULL DEFAULT TRUE, actor_id BIGINT NOT NULL REFERENCES users(id), INDEX(product_id,enabled,price),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS carts (
    user_id BIGINT NOT NULL REFERENCES users(id), variant_id BIGINT NOT NULL REFERENCES variants(id), quantity INT NOT NULL CHECK(quantity BETWEEN 1 AND 999), PRIMARY KEY(user_id,variant_id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS addresses (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL REFERENCES users(id), label VARCHAR(100) NOT NULL, detail VARCHAR(1000) NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS couriers (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL UNIQUE, logo VARCHAR(255) NOT NULL DEFAULT '', url VARCHAR(255) NOT NULL DEFAULT '',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS checkouts (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, checkout_no CHAR(36) NOT NULL UNIQUE, user_id BIGINT NOT NULL REFERENCES users(id), address VARCHAR(1100) NOT NULL, subtotal BIGINT NOT NULL, tax BIGINT NOT NULL, shipping BIGINT NOT NULL, total BIGINT NOT NULL, payment ENUM('waiting','paid','cancelled') NOT NULL DEFAULT 'waiting', paid_by BIGINT REFERENCES users(id), INDEX(user_id,id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, checkout_id BIGINT NOT NULL REFERENCES checkouts(id), shop_id BIGINT NOT NULL REFERENCES shops(id), shipping BIGINT NOT NULL, subtotal BIGINT NOT NULL, tax BIGINT NOT NULL, status ENUM('waiting_payment','waiting_shop','rejected','packing','delivery','completed','return_review','return_accepted','return_rejected','return_completed','cancelled') NOT NULL DEFAULT 'waiting_payment', courier_id BIGINT REFERENCES couriers(id), receipt VARCHAR(150) NOT NULL DEFAULT '', completed_at DATETIME, actor_id BIGINT NOT NULL REFERENCES users(id), UNIQUE(checkout_id,shop_id), INDEX(shop_id,status,id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS order_lines (
    order_id BIGINT NOT NULL REFERENCES orders(id), variant_id BIGINT NOT NULL REFERENCES variants(id), product_id BIGINT NOT NULL REFERENCES products(id), product_name VARCHAR(180) NOT NULL, variant_name VARCHAR(306) NOT NULL, price BIGINT NOT NULL, quantity INT NOT NULL, grams INT NOT NULL, PRIMARY KEY(order_id,variant_id), INDEX(product_id,order_id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS tracking (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL REFERENCES orders(id), note VARCHAR(1000) NOT NULL, actor_id BIGINT NOT NULL REFERENCES users(id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS returns (
    order_id BIGINT PRIMARY KEY REFERENCES orders(id), description TEXT NOT NULL, media JSON NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL REFERENCES orders(id), product_id BIGINT NOT NULL REFERENCES products(id), user_id BIGINT NOT NULL REFERENCES users(id), rating INT NOT NULL CHECK(rating BETWEEN 1 AND 5), body TEXT NOT NULL, media JSON NOT NULL, reply TEXT, actor_id BIGINT NOT NULL REFERENCES users(id), deleted BOOLEAN NOT NULL DEFAULT FALSE, UNIQUE(order_id,product_id), INDEX(product_id,deleted,id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB WITH SYSTEM VERSIONING;

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL REFERENCES users(id), message VARCHAR(500) NOT NULL, read_at DATETIME, INDEX(user_id,id),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS idempotency (
    actor_id BIGINT NOT NULL REFERENCES users(id), scope VARCHAR(150) NOT NULL, request_key CHAR(36) NOT NULL, fingerprint CHAR(64) NOT NULL, result_id BIGINT, PRIMARY KEY(actor_id,scope,request_key),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;

